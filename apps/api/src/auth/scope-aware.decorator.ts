import { SetMetadata } from '@nestjs/common';

export const SCOPE_AWARE = 'wetop:scope-aware';

/**
 * Маршрут сам решает, что показать человеку с областью доступа (DATA_MODEL §31.1): перехватчик не требует от него
 * выбранного филиала. Нужен выбору филиала и сводке по филиалам: они вызываются до выбора и обязаны отфильтровать ответ
 * по назначениям человека, иначе он увидел бы чужие филиалы. Без метки человек с областью получает 403 без выбранного места.
 */
export const ScopeAware = () => SetMetadata(SCOPE_AWARE, true);
