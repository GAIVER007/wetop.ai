import { describe, expect, it } from 'vitest';
import { listenHost } from './listen-host';

/**
 * Адрес, на котором слушает API (plans/server-kz-2026-09-17.md, шаг 0).
 *
 * На Mac API слушает только 127.0.0.1 — наружу его выпускает туннель, и так было с первого среза.
 * В Docker у каждой службы своя сеть: API на 127.0.0.1 контейнера не увидит ни стойка (`web`), ни
 * туннель (`cloudflared`), и compose не поднимется вовсе. Порты наружу при этом не публикуются
 * (`expose`, не `ports`), поэтому 0.0.0.0 внутри контейнера виден только соседям по сети compose.
 * Найдено 18.09.2026 параллельной сессией; тест без демона Docker этого не ловил.
 */
describe('listenHost', () => {
  it('по умолчанию 127.0.0.1 — как на Mac с первого среза', () => {
    expect(listenHost({})).toBe('127.0.0.1');
  });

  it('API_HOST задаёт адрес: в контейнере compose ставит 0.0.0.0', () => {
    expect(listenHost({ API_HOST: '0.0.0.0' })).toBe('0.0.0.0');
  });

  it('пустое или пробельное значение — умолчание, а не пустая строка', () => {
    expect(listenHost({ API_HOST: '' })).toBe('127.0.0.1');
    expect(listenHost({ API_HOST: '   ' })).toBe('127.0.0.1');
  });

  it('значение обрезается: перевод строки из .env не попадает в адрес', () => {
    expect(listenHost({ API_HOST: ' 0.0.0.0\n' })).toBe('0.0.0.0');
  });
});
