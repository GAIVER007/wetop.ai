import { describe, expect, it } from 'vitest';
import { viewerExclusion } from './company-scope';

/**
 * Один кабинет руководителя для всех главных администраторов (владелец 29.10.2026: Юрий владелец WETOP, Вячеслав
 * главный администратор со своим бизнесом Luxx). Компания WETOP это запись «WETOP (сайт)» (миграция 170): она не
 * клиент. Пока её нет, по-старому не клиент организация смотрящего; когда есть, организация смотрящего клиент,
 * и у Юрия, и у Вячеслава список одинаковый.
 */
describe('кого не считать клиентом в кабинете', () => {
  it('запись компании есть: смотрящий не исключается, его бизнес остаётся клиентом', () => {
    expect(viewerExclusion(new Set(['wetop-site']), 'luxx')).toBeNull();
  });
  it('записи компании нет: как раньше, своя организация смотрящего не клиент', () => {
    expect(viewerExclusion(new Set(), 'svyatoy')).toBe('svyatoy');
  });
  it('без организации у смотрящего: исключать некого', () => {
    expect(viewerExclusion(new Set(), null)).toBeNull();
  });
});
