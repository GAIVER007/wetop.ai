import { describe, expect, it } from 'vitest';
import { weekPeriod } from './week-period';

describe('calendar week boundaries', () => {
  it.each([
    ['2026-09-14', 0, '2026-09-14', '2026-09-20'],
    ['2026-09-16', 0, '2026-09-14', '2026-09-20'],
    ['2026-09-20', 0, '2026-09-14', '2026-09-20'],
    ['2026-09-30', 0, '2026-09-28', '2026-10-04'],
    ['2027-01-01', 0, '2026-12-28', '2027-01-03'],
    ['2028-02-29', 0, '2028-02-28', '2028-03-05'],
    ['2026-09-14', -1, '2026-09-07', '2026-09-13'],
    ['2026-12-28', 1, '2027-01-04', '2027-01-10'],
    ['2027-01-04', -1, '2026-12-28', '2027-01-03'],
  ])('%s, shift %i', (date, offset, from, to) => {
    expect(weekPeriod(date, offset)).toEqual({ from, to });
  });
});
