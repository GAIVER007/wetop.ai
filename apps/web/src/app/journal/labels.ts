/** `t` переводит подпись на язык человека; без него русский (тесты, сверка с API) */
export function actionLabel(code: string, t: Translate = RU): string {
  const known = ACTION_RU[code];
  if (known) return t(known);
  const section = SECTION_RU.find(([prefix]) => code.startsWith(prefix));
  return section ? t('Действие: {section}', { section: t(section[1]) }) : code;
}

export function entityLabel(type: string, t: Translate = RU): string {
  const known = ENTITY_RU[type];
  return known ? t(known) : type;
}
