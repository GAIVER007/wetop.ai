import { describe, expect, it } from 'vitest';
import { maskPhone } from './phone-mask';

/**
 * «Брони v2», R3 (ADR-106, ТЗ §11, §19): в быстром просмотре номер гостя не светится целиком — видно,
 * что телефон есть и чем он кончается; позвонить и написать можно кнопками. Полная карточка — как была.
 */
describe('телефон гостя в быстром просмотре', () => {
  it('казахстанский номер: код страны и две последние цифры', () => {
    expect(maskPhone('+7 701 000 00 12')).toBe('+7 *** *** ** 12');
    expect(maskPhone('+77010000012')).toBe('+7 *** *** ** 12');
  });
  it('без плюса и с другим кодом страны — тот же вид, код как был', () => {
    expect(maskPhone('87010000012')).toBe('8 *** *** ** 12');
    expect(maskPhone('+998 90 123 45 67')).toBe('+998 *** *** ** 67');
  });
  it('короткий номер — только хвост; пустого номера нет', () => {
    expect(maskPhone('1234')).toBe('*** 34');
    expect(maskPhone('7')).toBe('***');
    expect(maskPhone(null)).toBeNull();
    expect(maskPhone('   ')).toBeNull();
  });
});
