import { expect, it } from 'vitest';
import { almatyDate } from './almaty';

// Даты событий хранятся в UTC, а день для стойки и сверок — по часам объекта (AGENTS.md §13). Карточка брони
// показывала дату оплаты срезом UTC-строки: оплата в 01:30 по Алматы попадала во «вчера» (волна 3)
it('дата оплаты и возврата — по Алматы, а не по UTC', () => {
  expect(almatyDate('2026-09-13T20:30:00.000Z')).toBe('2026-09-14');
  expect(almatyDate('2026-09-14T18:59:59.000Z')).toBe('2026-09-14');
  expect(almatyDate('2026-09-14T19:00:00.000Z')).toBe('2026-09-15');
});

it('не дата — пустая строка, а не «Invalid Date» на экране', () => {
  expect(almatyDate('not-a-date')).toBe('');
});
