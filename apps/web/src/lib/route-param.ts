/**
 * Значение динамического сегмента адреса, пригодное для запроса к API.
 *
 * Next отдаёт `params` как есть, не декодируя: у адреса `/channels/events/test%3A2026-09-16…`
 * параметр приходит строкой `test%3A2026-09-16…`. Клиент API кодирует его ещё раз, получается
 * `test%253A…`, и сервер отвечает 404 на существующую запись — на живой стойке 17.09.2026 так
 * пропадали ревизии Channex, в чьих идентификаторах есть двоеточия (`test:<время>:<хеш>`).
 *
 * Битую последовательность (`%zz`, одинокий `%`) оставляем как есть: пусть сервер сам скажет, что
 * такой записи нет, — это лучше, чем уронить экран исключением.
 */
export function decodeRouteParam(value: string): string {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}
