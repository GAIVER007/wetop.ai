def sheet(title, cols, example, note, dv=None, rows=30, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = title
    ws['A1'] = note
    ws['A1'].font = Font(bold=True, size=12)
    ws['A1'].alignment = Alignment(wrap_text=True, vertical='top')
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max(len(cols), 2))
    ws.row_dimensions[1].height = 48
    for i, (name, width, req) in enumerate(cols, 1):
        c = ws.cell(row=2, column=i, value=name + (' *' if req else ''))
        c.font = Font(bold=True, color='FFFFFF')
        c.fill = HEAD
        c.alignment = Alignment(wrap_text=True, vertical='center')
        c.border = B
        ws.column_dimensions[get_column_letter(i)].width = width
        e = ws.cell(row=3, column=i, value=example[i - 1] if i - 1 < len(example) else None)
        e.font = EX
        e.border = B
        for r in range(4, 4 + rows):
            cell = ws.cell(row=r, column=i)
            cell.border = B
            if req:
                cell.fill = REQ
    ws.row_dimensions[2].height = 36
    ws.freeze_panes = 'A4'
    for col, values in (dv or {}).items():
        v = DataValidation(type='list', formula1='"' + ','.join(values) + '"', allow_blank=True)
        ws.add_data_validation(v)
        v.add(f'{col}4:{col}{3 + rows}')
    return ws

