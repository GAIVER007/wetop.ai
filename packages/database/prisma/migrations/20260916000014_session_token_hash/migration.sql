-- Отпечаток ключа сессии (срез 13, ADR-046).
--
-- Пропуск миграции 20260915000013: у sessions не было поля, по которому сессию ищут.
-- Без него единственным «ключом» становился бы сам id, а он лежит в базе открытым —
-- то есть утечка базы давала бы вход. У invites отпечаток был предусмотрен, у sessions нет.
--
-- NOT NULL без значения по умолчанию безопасен: таблица пуста, вход ещё не работал.
-- Если она вдруг не пуста, миграция честно упадёт, а не проставит всем одинаковую пустышку.

ALTER TABLE "sessions" ADD COLUMN "token_hash" VARCHAR(64) NOT NULL;

-- Отпечаток — HMAC-SHA256 в шестнадцатеричном виде: ровно 64 символа нижнего регистра.
-- База отвергает всё, что на отпечаток не похоже: пустую строку, обрезок, верхний регистр.
ALTER TABLE "sessions" ADD CONSTRAINT "sessions_token_hash_shape"
  CHECK ("token_hash" ~ '^[0-9a-f]{64}$');

-- Уникальность — не украшение: по этому полю идёт поиск сессии, и двух одинаковых быть не должно.
CREATE UNIQUE INDEX "sessions_token_hash_key" ON "sessions"("token_hash");
