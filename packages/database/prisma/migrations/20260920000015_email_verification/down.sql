-- Откат подтверждения почты (миграция 20260920000015_email_verification, ADR-060).
-- После отката регистрация снова открывает сессию сразу, выданные ссылки подтверждения перестают
-- работать, отметки «почта подтверждена» теряются — при повторном применении миграции её UPDATE
-- проставит их всем заведённым заново. Откатывать вместе с кодом до ADR-060: он читает `email_verified_at`.

DROP TABLE IF EXISTS "email_verifications";

ALTER TABLE "users" DROP COLUMN IF EXISTS "email_verified_at";
