-- DATA_MODEL v2.8 §17.2–17.3 (ADR-124), SEC-1b стадия B (Q-222, Q-225, решение владельца 30.09.2026): у роли запросов организации
-- `wetop_app` отзываются права на данные интеграции с менеджером каналов.
--
-- Было: миграция `…026_rls_roles` выдала `wetop_app` SELECT/INSERT/UPDATE/DELETE на все таблицы схемы, хотя §17.3 называет
-- `external_events`, `channel_outbox` и `system_incidents` таблицами без RLS, которые читает только служебный путь. Ошибка в запросе
-- организации (или инъекция) отдавала журнал событий Channex с телефонами и почтами гостей в ревизиях, очередь выгрузки и
-- инциденты сторожа всей установки.
--
-- Стало:
--   external_events   — никаких прав: журнал входящих событий читает и пишет только служебный путь;
--   system_incidents  — никаких прав: инциденты сторожа на всю установку, колонки property_id нет (ADR-124);
--   channel_outbox    — только INSERT (без RETURNING: его нельзя без SELECT): постановка изменения остатков в очередь остаётся в
--                       транзакции команды человека и откатывается вместе с ней. Читает, отправляет и правит очередь служебный путь.
-- Права `wetop_service` не меняются. Внешние ключи на `properties` проверяются от владельца таблицы и прав на неё не требуют.
--
-- Код API к этой миграции готов заранее (PR #188, #189, #198): все обращения к трём таблицам идут через `integrationTables(db)`
-- (служебная роль), очередь ставится `createMany`, разбор входящих ревизий из запроса организации — интеграционной командой
-- `runIntegrationCommand` на служебной роли. Порядок выкладки — сначала код, потом миграция (docs/ops/rls.md, «SEC-1b, стадия B»).
-- Прежний код после миграции сломал бы журнал и очередь каналов под организацией.
--
-- Идёт и в public, и в pms_test (ADR-042): права выдаются по current_schema(), как в …026 и …033.
DO $$
DECLARE s text := current_schema();
BEGIN
  EXECUTE format('REVOKE ALL ON TABLE %1$I.external_events, %1$I.system_incidents FROM wetop_app', s);
  EXECUTE format('REVOKE ALL ON TABLE %I.channel_outbox FROM wetop_app', s);
  EXECUTE format('GRANT INSERT ON TABLE %I.channel_outbox TO wetop_app', s);
END $$;
