/**
 * Регистрация (срез 13, ADR-046, DATA_MODEL §13).
 *
 * Регистрация — это запрос кода с побочным действием: если адреса ещё нет, заводятся организация,
 * человек и его членство, а пробный период отсчитывается от этой секунды. Дальше всё как при входе:
 * письмо с кодом, проверка, сессия. Ни второго пароля, ни второй формы у человека нет.
 *
 * Наружу регистрация на занятый адрес неотличима от регистрации на новый: и там и там уходит код.
 * Иначе форма регистрации становится справочником, есть ли у нас такой клиент. Разница только внутри:
 * занятому адресу новая организация не заводится — он получает код в свою старую.
 */

/** Как в колонке `organizations.name` — `varchar(200)`. */
export const ORGANIZATION_NAME_MAX = 200;

/** Название приводится к одному виду: обрезка по краям, один пробел вместо любой пачки пробелов. */
export function normalizeOrganizationName(raw: string): string {
  return raw.trim().replace(/\s+/g, ' ');
}

/** Пустое название и название длиннее колонки не принимаем. Остальное — дело человека. */
export function isOrganizationNameShaped(raw: string): boolean {
  const name = normalizeOrganizationName(raw);
  return name.length >= 1 && name.length <= ORGANIZATION_NAME_MAX;
}

/** Тексты для формы. Про почту и название говорим прямо: это ошибки ввода, не секрет. */
export const REGISTRATION_EMAIL_MESSAGE = 'Укажите почту, на которую придёт код для входа.';
export const REGISTRATION_NAME_MESSAGE = `Укажите название организации, до ${ORGANIZATION_NAME_MAX} знаков.`;
