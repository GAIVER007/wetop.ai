const NAMES = new Map(CITIZENSHIP_COUNTRIES.map((c) => [c.code, c.name]));

/** Название страны по коду; неизвестный код из старых данных показывается как есть */
export function citizenshipLabel(code: string | null | undefined): string | null {
  const c = (code ?? '').trim().toUpperCase();
  if (!c) return null;
  return NAMES.get(c) ?? c;
}

/** Страны, где гражданство гостя обязательно к заселению (регистрация иностранцев eQonaq) */
const CHECK_IN_CITIZENSHIP_COUNTRIES = new Set(['KZ']);

/** Нужно ли гражданство для заселения в гостинице этой страны (ISO alpha-2 объекта) */
export function citizenshipRequiredForCheckIn(propertyCountry: string | null | undefined): boolean {
  const c = (propertyCountry ?? '').trim().toUpperCase();
  return c === '' || CHECK_IN_CITIZENSHIP_COUNTRIES.has(c);
}
