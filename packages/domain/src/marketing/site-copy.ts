/** Вариант текста по номеру (по кругу) с названием филиала */
export function siteCopySuggestion(vertical: SiteFactsVertical, index: number, name: string): SiteCopyVariant {
  const list = COPY[vertical];
  const v = list[((index % list.length) + list.length) % list.length]!;
  const fill = (s: string) => s.replaceAll('{name}', name.trim() || 'Мы');
  return { heading: fill(v.heading), subheading: fill(v.subheading), about: fill(v.about) };
}

export const SITE_COPY_COUNT = (vertical: SiteFactsVertical): number => COPY[vertical].length;
