/**
 * Вариант текста по номеру (по кругу) с названием филиала. С фактами филиала первый экран берётся из `heroCopy`
 * (фраза под тон стиля, название и разделы в подзаголовке); «О нас» из готовых вариантов
 */
export function siteCopySuggestion(
  vertical: SiteFactsVertical,
  index: number,
  name: string,
  facts?: SiteFacts | null,
  tone: HeroTone = 'CLEAN',
  locale: HeroLocale = 'ru',
): SiteCopyVariant {
  const list = COPY[vertical];
  const v = list[((index % list.length) + list.length) % list.length]!;
  const fill = (s: string) => s.replaceAll('{name}', name.trim() || 'Мы');
  const hero = facts && facts.vertical === vertical ? heroCopy(facts, tone, index, locale) : null;
  return { heading: hero?.heading ?? fill(v.heading), subheading: hero?.subheading ?? fill(v.subheading), about: fill(v.about) };
}

export const SITE_COPY_COUNT = (vertical: SiteFactsVertical): number => COPY[vertical].length;
