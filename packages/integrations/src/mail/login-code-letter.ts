/**
 * Письмо с одноразовым кодом входа (срез 13, ADR-046).
 *
 * Правила, из которых собран текст:
 * 1. Письмо уходит на адрес, который ещё никто не подтвердил. Значит в нём нет ни имени человека,
 *    ни названия организации, ни чего-либо ещё, что можно узнать, подставив чужую почту.
 * 2. Ссылок нет вообще. Письмо с кодом и ссылкой — образец фишингового письма; мы такому не учим.
 *    Код человек вводит на той же вкладке, где его запросил.
 * 3. Один язык, русский. Второй появится вместе с языками на стойке, не раньше.
 *
 * Срок жизни кода приходит снаружи, числом. Этот слой не знает ни про домен, ни про его правила:
 * знать их — забота того, кто письмо заказывает (ADR-004, границы слоёв).
 */

import type { MailMessage } from './sender';

export const LOGIN_CODE_SUBJECT = 'Код для входа в WETOP';

/** Склоняем «минуту» руками: ради одного слова тянуть библиотеку не будем. */
export function minutesWord(n: number): string {
  const tail = n % 100;
  if (tail >= 11 && tail <= 14) return 'минут';
  switch (n % 10) {
    case 1:
      return 'минуту';
    case 2:
    case 3:
    case 4:
      return 'минуты';
    default:
      return 'минут';
  }
}

export function loginCodeLetter(to: string, code: string, ttlMs: number): MailMessage {
  const m = Math.max(1, Math.round(ttlMs / 60_000));
  const text = [
    `Код для входа: ${code}`,
    '',
    `Он действует ${m} ${minutesWord(m)} и подходит один раз.`,
    'Введите его на той странице, где запрашивали.',
    '',
    'Если вход запрашивали не вы — просто не отвечайте на это письмо. Без кода в систему не войти.',
    '',
    'WETOP',
  ].join('\n');
  return { to, subject: LOGIN_CODE_SUBJECT, text };
}
