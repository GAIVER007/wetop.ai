import { normalizeCitizenship } from '@pms/domain';

/**
 * Q-118: что писать в `citizenship` существующего гостя при повторном импорте.
 *
 * Гражданство — поле заселения, а не импорта (DATA_MODEL §3): у броней каналов Exely его не отдаёт,
 * код с паспорта вводит стойка. Раньше импорт писал весь набор полей, и ночная синхронизация суток
 * затирала введённое пустым значением из Exely — заселение блокировалось заново.
 *
 * Правило: пустое из Exely не затирает то, что есть в PMS; пустое в PMS заполняется кодом из Exely;
 * когда код есть у обоих, Exely остаётся источником истины (как и по остальным полям гостя).
 *
 * @returns код для записи или `undefined` — поле не попадает в `update`, значение в базе не меняется.
 *          Чистка старых '   ' в NULL — отдельное решение владельца (Q-117), импорт её не делает.
 */
export function guestCitizenshipOnUpdate(incoming: string | null | undefined): string | undefined {
  // Пусто из Exely → undefined: колонка не попадает в update и в базе остаётся как есть
  return normalizeCitizenship(incoming) ?? undefined;
}
