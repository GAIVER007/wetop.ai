import { describe, expect, it } from 'vitest';
import { chunk } from './chunk';

/**
 * Чистка гражданства (Q-117) валилась на живой dev-БД: 401 идентификатор в одном `updateMany`
 * плюс 401 строка журнала не укладывались в таймаут интерактивной транзакции Prisma (5 с).
 * Пачками — каждая транзакция короткая и укладывается даже через пулер в другом регионе.
 */
describe('chunk', () => {
  it('режет список на пачки заданного размера, последняя — короче', () => {
    expect(chunk([1, 2, 3, 4, 5], 2)).toEqual([[1, 2], [3, 4], [5]]);
    expect(chunk([1, 2, 3, 4], 2)).toEqual([
      [1, 2],
      [3, 4],
    ]);
  });
  it('список короче пачки — одна пачка; пустой — ни одной', () => {
    expect(chunk(['a'], 100)).toEqual([['a']]);
    expect(chunk([], 100)).toEqual([]);
  });
  it('размер пачки меньше единицы недопустим — молчаливая бесконечная петля хуже падения', () => {
    expect(() => chunk([1, 2], 0)).toThrow(/размер пачки/);
    expect(() => chunk([1, 2], -5)).toThrow(/размер пачки/);
  });
});
