"""Данные слоёв защиты 1–3: невидимые символы, гомоглифы, словарь крещендо
и паттерны намерений. Логики здесь нет — она в guardrails.py.

🔴 Паттерн не ослабляют из-за одного ложного срабатывания: случай идёт
в tests/guard_corpus.py (FALSE_POSITIVES), паттерн уточняется. Бытовые
«правила проживания», «режим работы», «инструкция по заселению» паттерны
refuse ловить не должны — только сочетания с глаголами смены роли,
показа или сброса.
"""

from __future__ import annotations

import re

# ─── Слой 1. Невидимые символы ───
# Нулевой ширины и соединители, служебная плоскость (в ней прячется целая
# фраза, а строка выглядит пустой), селекторы начертания, мягкий перенос.
INVISIBLE_CHARS: frozenset[str] = frozenset(
    [chr(c) for c in range(0x200B, 0x2010)]
    + [chr(c) for c in range(0x2060, 0x2065)]
    + ["﻿", "­"]
    + [chr(c) for c in range(0xE0000, 0xE0080)]
    + [chr(c) for c in range(0xFE00, 0xFE10)]
    + [chr(c) for c in range(0xE0100, 0xE01F0)]
)

# ─── Слой 1. Гомоглифы: латиница, притворяющаяся кириллицей ───
HOMOGLYPHS_LATIN_TO_CYR: dict[str, str] = {
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х",
    "y": "у", "k": "к", "h": "н", "m": "м", "t": "т", "b": "ь",
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К",
    "M": "М", "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
}

# ─── Слой 3. Словарь крещендо (целые слова, без учёта регистра) ───
CRESCENDO_WORDS: tuple[str, ...] = (
    "правила", "инструкции", "инструкция", "промпт", "роль", "режим",
    "забудь", "игнорируй", "притворись", "вообрази", "разработчик",
    "prompt", "instructions", "ignore", "pretend", "developer",
)


def _rx(pattern: str, flags: int = re.IGNORECASE) -> re.Pattern[str]:
    return re.compile(pattern, flags)


# Глаголы показа и объекты, которые в бытовой речи не встречаются:
# «расскажи про инструкцию по заселению» сюда не попадает, потому что
# нет ни «промпт», ни притяжательного «свои/твои/системные».
_SHOW_VERBS = (
    r"(?:покажи|выведи|скажи|напиши|раскрой|расскажи|процитируй|повтори"
    r"|отправь|пришли|дай|озвучь|напечатай|перескажи)(?:те)?"
)
_OWN = r"(?:сво[иеёй]\w*|тво[иеёй]\w*|начальн\w*|скрыт\w*|исходн\w*|секретн\w*|внутренн\w*)"
_RESET_VERBS = (
    r"(?:забудь|отбрось|сотри|игнорируй|проигнорируй|отмени)(?:те)?"
    r"|не\s+учитывай(?:те)?"
)

