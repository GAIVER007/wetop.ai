import {beforeAll,afterAll,it,expect,vi} from 'vitest';
import {randomUUID} from 'node:crypto';
import {createPrismaClient} from '@pms/database';
import {withSignedInUser} from '../../apps/api/src/auth/request-context';
import {OwnerSummaryService} from '../../apps/api/src/finance/owner-summary';
import type {PrismaService} from '../../apps/api/src/database/prisma.provider';
import {RestaurantService} from '../../apps/api/src/food-service/restaurant.service';
import type {FoodScope} from '../../apps/api/src/food-service/scope';
import type {StockService} from '../../apps/api/src/food-service/stock.service';
const db=createPrismaClient('postgresql://owner_home_test@127.0.0.1:55516/wetop_owner_home','pms_test');
let s:FoodScope,employee:string;
const user=randomUUID();
const at=<T>(fn:()=>Promise<T>)=>withSignedInUser({userId:user,organizationId:s.organizationId,role:'OWNER',scope:'LOCATION',businessId:s.businessId,locationId:s.locationId,vertical:'FOOD_SERVICE'},fn);
const writer=new RestaurantService({db} as PrismaService,null,{} as StockService);
const service={payout:(id:string,body:unknown)=>at(()=>writer.payout(id,body))};
beforeAll(async()=>{
 const org=await db.organization.create({data:{name:'Synthetic payroll',status:'ACTIVE'}});
 await db.user.create({data:{id:user,name:'Synthetic payroll owner',email:`payroll-${user}@example.invalid`}});
 const b=await db.business.create({data:{organizationId:org.id,name:'Synthetic payroll',vertical:'FOOD_SERVICE'}});
 const l=await db.location.create({data:{businessId:b.id,name:'Synthetic payroll',timezone:'Asia/Almaty',currency:'KZT'}});
 s={organizationId:org.id,businessId:b.id,locationId:l.id,timezone:l.timezone,currency:l.currency,vertical:'FOOD_SERVICE'};
 employee=(await db.employee.create({data:{businessId:b.id,name:'Synthetic employee',paySetting:{create:{model:'FIXED',fixedMinor:100000n,percent:0,currency:'KZT'}}}})).id;
 await db.restaurantCashOperation.create({data:{locationId:l.id,kind:'INCOME',method:'CASH',amount:1000000n,currency:'KZT'}});
 // Full request scope, permissions and transaction are exercised, without writer spies.
 vi.stubEnv('EXPENSE_LINKS_ENABLED','1');
});
afterAll(async()=>{vi.restoreAllMocks();vi.unstubAllEnvs();await db.$disconnect();});
it('actual payroll writer replays sequential and concurrent intents and rejects changed payload',async()=>{
 const body={period:'2026-10',method:'CASH',amount:1000,idempotencyKey:randomUUID()};
 const first=await service.payout(employee,body);
 expect(await service.payout(employee,body)).toEqual(first);
 await expect(service.payout(employee,{...body,amount:1001})).rejects.toMatchObject({status:409});
 await expect(service.payout(employee,{period:body.period,method:'CASH',amount:1})).rejects.toMatchObject({status:400});
 const next={...body,idempotencyKey:randomUUID()};
 const results=await Promise.all([service.payout(employee,next),service.payout(employee,next)]);
 expect(results[0]).toEqual(results[1]);
 const ops=await db.restaurantCashOperation.findMany({where:{locationId:s.locationId,kind:'EXPENSE'}});
 expect(ops).toHaveLength(2);
 expect(ops.reduce((n,o)=>n+o.amount,0n)).toBe(2000n);
 const linked=await db.$queryRaw<Array<{id:string;code:string;paid:bigint}>>`SELECT d.id,c.code,expense_paid_minor(d.id) AS paid FROM expense_documents d JOIN expense_categories c ON c.id=d.category_id WHERE d.location_id=${s.locationId}::uuid`;
 expect(linked).toHaveLength(2);expect(linked.every(d=>d.code==='PAYROLL'&&d.paid===1000n)).toBe(true);
 await db.restaurantCashOperation.update({where:{id:first.id},data:{status:'VOIDED',voidedAt:new Date()}});
 expect(await service.payout(employee,body)).toEqual(first);
 const history=await db.$queryRaw<Array<{n:bigint}>>`SELECT count(*) AS n FROM expense_settlements WHERE location_id=${s.locationId}::uuid`;
 expect(history[0]?.n).toBe(2n);
 const sum=await db.restaurantCashOperation.aggregate({where:{locationId:s.locationId,kind:'EXPENSE',status:'COMPLETED'},_sum:{amount:true}});
 expect(sum._sum.amount).toBe(1000n);
 const summary=new OwnerSummaryService({db} as PrismaService);
 const report=await at(()=>summary.report('month'));
 expect(report.current.paidExpenses.currencies?.[0]).toMatchObject({currency:'KZT',paidMinor:'1000',categories:[{categoryName:'Оплата труда',paidMinor:'1000'}]});
 const paid=await db.$queryRaw<Array<{id:string;n:bigint}>>`SELECT d.id,expense_paid_minor(d.id) AS n FROM expense_documents d JOIN expense_settlements s ON s.expense_document_id=d.id WHERE s.restaurant_cash_operation_id=${first.id}::uuid`;
 expect(paid[0]?.n).toBe(0n);
 await expect(db.$executeRaw`UPDATE expense_documents SET amount_minor=1234 WHERE id=${paid[0]!.id}::uuid`).rejects.toThrow(/history immutable/);
 const foreign=await db.employee.findFirstOrThrow({where:{businessId:{not:s.businessId}}});
 await expect(service.payout(foreign.id,{...body,idempotencyKey:randomUUID()})).rejects.toMatchObject({status:404});
});
