import { test, expect, type Page } from '@playwright/test';
import { randomUUID } from 'node:crypto';
const api=`http://127.0.0.1:${process.env.ONBOARDING_REAL_API_PORT || '55844'}`;
async function actorHeaders(page: Page) {
  const cookies=await page.context().cookies();
  const session=cookies.find(c=>c.name==='wetop_session')?.value;
  const scope=cookies.find(c=>c.name==='wetop_scope')?.value;
  if(!session || !scope) throw new Error('Synthetic auth context missing');
  return {'x-wetop-session':session,'x-wetop-scope':decodeURIComponent(scope)};
}
test('real trial owner saves schedule, reloads persisted week and sees onboarding completed',async({page})=>{
  const email=`onboarding-recovery-schedule-${randomUUID()}@example.invalid`;
  const registered=await page.request.post(`${api}/auth/register`,{data:{email,name:'Synthetic owner',businessName:'Synthetic salon',vertical:'BEAUTY',password:'Synthetic-Schedule-2026!a',phoneCountry:'KZ',phone:'7000000000',privacyAccepted:true}});
  expect(registered.ok(),`register ${registered.status()}`).toBe(true);
  const mail=await(await page.request.get(`${api}/__onboarding-test/mail?email=${encodeURIComponent(email)}`)).json();
  expect(mail.link).toBeTruthy();
  await page.goto(mail.link);
  await expect(page.getByRole('heading',{level:1})).toHaveText('Добро пожаловать в WETOP');
  await page.getByRole('button',{name:'Настроить салон',exact:true}).click();
  await page.getByRole('button',{name:'Сохранить и продолжить',exact:true}).click();
  await expect(page.getByRole('region',{name:'Первые шаги',exact:true}).getByText('Выполнено 0 из 4 обязательных шагов',{exact:true})).toBeVisible();
  const headers=await actorHeaders(page);
  const runtime=await page.request.get(`${api}/__onboarding-test/runtime-role`,{headers});
  expect(runtime.ok()).toBe(true);
  expect(await runtime.json()).toEqual([{role:'wetop_app',rolsuper:false,rolbypassrls:false,owned:0}]);
  const svcResponse=await page.request.post(`${api}/beauty/services`,{headers,data:{name:'Synthetic service',durationMinutes:60,priceMinor:'10000',currency:'KZT'}});
  expect(svcResponse.ok()).toBe(true);
  const service=await svcResponse.json();
  expect((await page.request.put(`${api}/beauty/services/${service.id}/location`,{headers,data:{enabled:true}})).ok()).toBe(true);
  const staffResponse=await page.request.post(`${api}/beauty/employees`,{headers,data:{name:'Synthetic master'}});
  expect(staffResponse.ok()).toBe(true);
  const employee=await staffResponse.json();
  expect((await page.request.put(`${api}/beauty/employees/${employee.id}/services`,{headers,data:{serviceIds:[service.id]}})).ok()).toBe(true);
  await page.reload();
  await expect(page.getByRole('region',{name:'Первые шаги',exact:true}).getByText('Выполнено 3 из 4 обязательных шагов',{exact:true})).toBeVisible();
  await page.getByRole('link',{name:'Настроить график',exact:true}).click();
  await page.getByRole('main').getByRole('button',{name:'Synthetic master',exact:true}).click();
  let panel=page.getByRole('dialog');
  await panel.getByRole('group',{name:'Понедельник',exact:true}).getByRole('button',{name:'Сделать рабочим',exact:true}).click();
  await expect(panel.getByLabel('Понедельник: начало')).toHaveValue('09:00');
  await expect(panel.getByLabel('Понедельник: конец')).toHaveValue('18:00');
  await panel.getByRole('button',{name:'Сохранить график',exact:true}).click();
  await expect(panel.getByRole('status')).toHaveText('График сохранён');
  const read=async()=> (await page.request.get(`${api}/beauty/schedule?employee=${employee.id}`,{headers})).json();
  const saved=await read();
  expect(saved.week[0].intervals).toEqual([{timeFrom:'09:00',timeTo:'18:00'}]);
  await page.keyboard.press('Escape');
  await page.getByRole('link',{name:'Вернуться к настройке салона',exact:true}).click();
  await expect(page.getByRole('region',{name:'Первые шаги',exact:true}).getByText('Выполнено 4 из 4 обязательных шагов',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('region',{name:'Первые шаги',exact:true}).getByText('Выполнено 4 из 4 обязательных шагов',{exact:true})).toBeVisible();
  await page.goto('/beauty/schedule');
  await page.getByRole('main').getByRole('button',{name:'Synthetic master',exact:true}).click();
  panel=page.getByRole('dialog');
  await expect(panel.getByLabel('Понедельник: начало')).toHaveValue('09:00');
  await panel.getByLabel('Понедельник: начало').fill('10:00');
  await panel.getByRole('button',{name:'Сохранить график',exact:true}).click();
  await expect(panel.getByRole('status')).toHaveText('График сохранён');
  expect((await read()).week[0].intervals).toEqual([{timeFrom:'10:00',timeTo:'18:00'}]);
  const stale=await page.request.put(`${api}/beauty/employees/${employee.id}/working-hours`,{headers,data:{intervals:[],expectedRevision:saved.weekRevision}});
  expect(stale.status()).toBe(409);
  expect((await read()).week[0].intervals).toEqual([{timeFrom:'10:00',timeTo:'18:00'}]);
  await page.screenshot({path:test.info().outputPath('schedule-save-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:test.info().outputPath('schedule-save-mobile.png'),fullPage:true});
  const demoted=await page.request.post(`${api}/__onboarding-test/recovery`,{headers,data:{mode:'STAFF'}});
  expect(demoted.ok()).toBe(true);
  const current=await read();
  const denied=await page.request.put(`${api}/beauty/employees/${employee.id}/working-hours`,{headers,data:{intervals:[],expectedRevision:current.weekRevision}});
  expect(denied.status()).toBe(403);
  expect((await read()).week).toEqual(current.week);
});
